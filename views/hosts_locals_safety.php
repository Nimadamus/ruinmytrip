    <h1 class="hl-h2" style="font-size:clamp(1.8rem,4vw,2.5rem)">Safety for Hosts &amp; Locals</h1>
    <p class="hl-callout"><b>In an emergency, call the local emergency number first</b> (112 across the EU and many other countries, 911 in North America, 999 in the UK). RuinMyTrip cannot send help.</p>

    <h2>What we check, and what we do not</h2>
    <ul>
      <li><b>Email confirmed</b> means the member clicked a link sent to their address. It says nothing else about them.</li>
      <li><b>Adults only.</b> Meeting travelers, posting trips and hosting need a date of birth showing 18 or over. We do not check documents for this.</li>
      <li><b>Host applications</b> are read by a moderator before they appear. That is a review of what the member wrote, not a background check.</li>
      <li><b>We do not check identity documents.</b> A name and photo on a profile are what the member chose to show.</li>
    </ul>
    <p><b>Nothing on this site guarantees personal safety.</b> RuinMyTrip does not guarantee the safety, identity or behaviour of any member, host, guest or meetup.</p>

    <h2>Before you meet</h2>
    <ul>
      <li>Read their profile, their references and how long they have been a member.</li>
      <li>Keep the conversation on RuinMyTrip until you have met, so it can be reported if needed.</li>
      <li>Meet the first time somewhere public and busy, in daylight if you can.</li>
      <li>Tell a friend who you are meeting, where and when, and check in afterwards.</li>
      <li>Arrange your own way there and back, and keep your phone charged.</li>
      <li>Never send money, documents or account codes to another member, for any reason.</li>
    </ul>

    <h2>If something feels wrong</h2>
    <ul>
      <li>Leave. You never owe anybody your time, and you do not need a reason.</li>
      <li><b>Block</b> from their profile or the conversation menu. They can no longer message you or find you in searches.</li>
      <li><b>Report</b> the profile, a message or a reference. Every report is reviewed by a moderator, and the member is not told who reported them.</li>
      <li>If you were hurt or threatened, contact the police as well as reporting it here.</li>
    </ul>

    <h2>What is not allowed</h2>
    <p>Harassment, threats, unwanted sexual advances, discrimination, scams, asking for money, fake profiles, and using Hosts &amp; Locals for dating, commercial tours or paid lodging. Members who break these rules are suspended. The full rules are in our <a href="<?= e(url('guidelines')) ?>">community guidelines</a>.</p>

    <h2>Your privacy</h2>
    <ul>
      <li>Your email and phone number are never shown to other members.</li>
      <li>Profiles show a city. A host can add a neighbourhood. No address, street or live location is ever stored or shown.</li>
      <li>Stop being a local, or pause or withdraw hosting, any time from <a href="<?= e(url('hosts-locals/me')) ?>">your Hosts &amp; Locals settings</a>.</li>
      <li>You can delete your account and its data from <a href="<?= e(url('settings')) ?>">settings</a>. See our <a href="<?= e(url('privacy')) ?>">privacy policy</a>.</li>
    </ul>

    <h2>Overnight stays</h2>
    <ul>
      <li>Stays are free. Never send or accept money, a deposit or a "booking fee". Anybody asking for one is breaking our rules: report them.</li>
      <li>Read the host's or guest's profile and references, and the house rules, before you say yes.</li>
      <li>Agree arrival details in RuinMyTrip messages, and share the address and your dates with a friend.</li>
      <li>Keep your passport, money and phone with you, and have a backup place to stay in mind.</li>
      <li>Every stay page has a <b>Report this stay</b> link for the guest and the host. Moderators review every report.</li>
    </ul>
